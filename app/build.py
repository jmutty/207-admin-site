#!/usr/bin/env python3
"""Build 207 Admin (207photo.com/207-admin/).

Since 2026-09-27 the app is NOT pasted into Elementor. It is one hosted file:
  dist/207-admin.js   styles + page markup + app code, uploaded to Supabase Storage by deploy.sh
  wordpress-embed.html  the tiny loader that lives in the Elementor HTML widget (rarely changes)
Sources: src/shell.html (styles + frame + nav + Today), section partials src/*.html, JS parts in order.
"""
import json, os, re, subprocess, sys
os.chdir(os.path.dirname(os.path.abspath(__file__)))

JS_PARTS = ["src/shell-top.js", "src/pickers.js", "src/places.js", "src/access.js", "src/savedviews.js", "src/jobs.js", "src/jobs-calculator.js", "src/parents.js", "src/partners-prospect-tools.js",
            "src/partners-orgs.js", "src/partners-library.js", "src/bookings.js", "src/bookings-library.js", "src/partners-hub.js", "src/system.js", "src/outbox.js", "src/settings-sending.js", "src/team.js", "src/push.js", "src/welcome.js", "src/scheduling.js", "src/assignments.js", "src/inventory.js", "src/timeclock.js", "src/staffrecords.js", "src/partners-follow.js", "src/results.js", "src/openjobs.js", "src/workflows.js", "src/jobpage.js", "src/timeclock-extra.js", "src/emails.js", "src/jobchecklist.js", "src/listviews.js", "src/crew.js", "src/shell-end.js"]
HTML_PARTS = ["src/jobs.html", "src/parents.html", "src/partners.html", "src/system.html", "src/team.html", "src/staff.html", "src/inventory.html", "src/timeclock.html", "src/staffrecords.html", "src/partners-follow.html", "src/results.html", "src/openjobs.html", "src/workflows.html", "src/jobpage.html", "src/emails.html", "src/crew.html"]
APP_URL = "https://socluffmclkdljtmiexw.supabase.co/storage/v1/object/public/admin-app/207-admin.js"

# 1. App code (shared scope, one function body), syntax-checked.
app = "// GENERATED by build.py from admin-page/src/ -- edit the files in src/, not this one.\n"
for f in JS_PARTS:
    app += f"\n  // ---------- {f} ----------\n" + open(f).read()
open("admin-dashboard.js", "w").write(app)
subprocess.run(["node", "--check", "admin-dashboard.js"], check=True)

# 2. Styles + markup out of the shell, sections dropped in.
shell = open("src/shell.html").read()
css = shell[shell.index("<style>") + 7: shell.index("</style>")]
markup = shell[shell.index('<div class="aca">'): shell.index("<script>", shell.index('<div class="aca">'))].rstrip()
sections = "\n".join(open(f).read() for f in HTML_PARTS)
markup = markup.replace("<!-- __SECTIONS__ -->", sections)
for p in HTML_PARTS + ["src/shell.html"]:
    if re.search(r"[^\x00-\x7f]", open(p).read()):
        sys.exit(f"FAIL: {p} has non-ASCII characters (use HTML entities)")
ids = re.findall(r'id="(aca-panel-[a-z]+)"', markup)
if len(ids) != len(set(ids)):
    sys.exit("FAIL: duplicate panel ids")

# 3. The hosted file: inject styles + markup into #aca-root, then run the app (it waits for supabase-js).
bundle = ("/* 207 Admin -- built by admin-page/build.py. Do not edit; edit admin-page/src/. */\n"
          "(function () {\n"
          "  var root = document.getElementById('aca-root');\n"
          "  if (!root || root.getAttribute('data-mounted')) return;\n"
          "  root.setAttribute('data-mounted', '1');\n"
          "  var st = document.createElement('style');\n"
          f"  st.textContent = {json.dumps(css)};\n"
          "  document.head.appendChild(st);\n"
          # The app's typeface (Source Sans 3). admin.207photo.com's CSP allows fonts.googleapis.com + fonts.gstatic.com.
          "  if (!document.querySelector('link[data-aca-font]')) { var f = document.createElement('link'); f.rel = 'stylesheet'; f.setAttribute('data-aca-font', '1');\n"
          "    f.href = 'https://fonts.googleapis.com/css2?family=Source+Sans+3:wght@400;600;700&display=swap'; document.head.appendChild(f); }\n"
          f"  root.innerHTML = {json.dumps(markup)};\n"
          # iPhone "Add to Home Screen": use the 207 Admin icon (logo without the tagline, padded) and name
          # instead of the WordPress site icon. Only on this page; the rest of 207photo.com is unchanged.
          "  var ICON = 'https://socluffmclkdljtmiexw.supabase.co/storage/v1/object/public/admin-app/icons/';\n"
          "  document.querySelectorAll('link[rel=\"apple-touch-icon\"],link[rel=\"apple-touch-icon-precomposed\"]').forEach(function (l) { l.remove(); });\n"
          "  [['apple-touch-icon', 'apple-touch-icon.png', '180x180'], ['icon', 'admin-icon-192.png', '192x192']].forEach(function (x) {\n"
          "    var l = document.createElement('link'); l.rel = x[0]; l.href = ICON + x[1]; l.sizes = x[2]; document.head.appendChild(l); });\n"
          "  [['apple-mobile-web-app-title', '207 Admin']].forEach(function (x) {\n"
          "    var m = document.createElement('meta'); m.name = x[0]; m.content = x[1]; document.head.appendChild(m); });\n"
          "})();\n" + app)
os.makedirs("dist", exist_ok=True)
open("dist/207-admin.js", "w").write(bundle)
subprocess.run(["node", "--check", "dist/207-admin.js"], check=True)

# 4. The Elementor loader (paste once; only changes if the file URL or supabase-js changes).
loader = f"""<!-- 207 ADMIN (loader). The app is hosted at {APP_URL}
     and deployed with admin-page/deploy.sh. Source: admin-page/src/. Do not paste the app here.
     The ?v= minute stamp stops Supabase's CDN from serving a stale copy after a deploy. -->
<div id="aca-root"></div>
<script src="https://cdn.jsdelivr.net/npm/@supabase/supabase-js@2.117.2/dist/umd/supabase.js" integrity="sha384-Rj26LVGvoeRVR6+mwQmFfcR3QOBEwT+ZmuCWpuiqeTzJpCs0ER4ITAWGb4Hiy3Ok" crossorigin="anonymous"></script>
<script>
(function () {{
  var s = document.createElement("script");
  s.src = "{APP_URL}?v=" + Math.floor(Date.now() / 60000);
  document.body.appendChild(s);
}})();
</script>
"""
if re.search(r"[&<>]", loader.split("<script>")[1].split("</script>")[0]):
    sys.exit("FAIL: loader script contains characters WordPress may mangle")
open("wordpress-embed.html", "w").write(loader)
print(f"OK: dist/207-admin.js {len(bundle)//1024} KB, loader {len(loader)} bytes, {len(ids)} panels")
